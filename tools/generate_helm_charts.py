HEADER = """# Generated by tools/generate_helm_charts.py from helm/microservice.
# Edit the generic chart or the generator, then regenerate; do not hand-edit.
"""


def build_values(name: str, spec: dict) -> dict:
    port = spec["port"]
    values: dict = {
        "replicaCount": spec["replicas"],
        "image": {"repository": f"platform/{name}", "tag": "1.0.0",
                  "pullPolicy": "IfNotPresent"},
        "containerPort": port,
        "service": {"type": "ClusterIP", "port": spec.get("servicePort", port), "name": "http"},
        "configMapRef": spec.get("configMapRef", "platform-config"),
        "env": [{"name": "APP_ENV", "value": "development"}],
        "secretEnv": spec.get("secretEnv", []),
        "resources": spec["resources"],
        "probes": spec.get("probes", {
            "startup": {"enabled": True, "path": "/health/live", "periodSeconds": 3,
                        "failureThreshold": 30},
            "liveness": {"enabled": True, "path": "/health/live", "periodSeconds": 15,
                         "timeoutSeconds": 3, "failureThreshold": 3},
            "readiness": {"enabled": True, "path": "/health/ready", "periodSeconds": 5,
                          "timeoutSeconds": 3, "failureThreshold": 3},
        }),
        "podAnnotations": spec.get("podAnnotations",
                                   {"prometheus.io/scrape": "true", "prometheus.io/path": "/metrics"}),
        "podSecurityContext": spec.get("podSecurityContext", {
            "runAsNonRoot": True, "runAsUser": 10001, "runAsGroup": 10001, "fsGroup": 10001,
            "seccompProfile": {"type": "RuntimeDefault"},
        }),
        "securityContext": {"allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True,
                            "capabilities": {"drop": ["ALL"]}},
        "serviceAccount": {"create": False, "name": "", "automount": False},
        "autoscaling": spec.get("autoscaling", {"enabled": False}),
        "pdb": {"enabled": True, "minAvailable": 1},
        "terminationGracePeriodSeconds": 30,
    }
    if spec.get("extraVolumes"):
        values["extraVolumes"] = spec["extraVolumes"]
        values["extraVolumeMounts"] = spec["extraVolumeMounts"]
    if spec.get("database"):
        values["secretEnv"] = [
            {"name": "INTERNAL_API_TOKEN", "secretName": SECRET, "key": "INTERNAL_API_TOKEN"},
            {"name": "POSTGRES_PASSWORD", "secretName": SECRET, "key": "POSTGRES_PASSWORD"},
        ]
        values["env"].append({
            "name": "DATABASE_URL",
            "value": "postgresql+asyncpg://platform:$(POSTGRES_PASSWORD)@postgres:5432/"
                     + spec["database"],
        })
    return values


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, spec in SERVICES.items():
        target = OUT / name
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(SOURCE / "templates", target / "templates")
        chart = {
            "apiVersion": "v2",
            "name": name,
            "description": spec["description"],
            "type": "application",
            "version": "1.0.0",
            "appVersion": "1.0.0",
            "kubeVersion": ">=1.27.0-0",
            "keywords": ["kubernetes", "gitops", name],
            "maintainers": [{"name": "Platform Engineering"}],
        }
        (target / "Chart.yaml").write_text(
            HEADER + yaml.safe_dump(chart, sort_keys=False), encoding="utf-8"
        )
        (target / "values.yaml").write_text(
            HEADER + yaml.safe_dump(build_values(name, spec), sort_keys=False), encoding="utf-8"
        )
        print(f"generated helm/charts/{name}")


if __name__ == "__main__":
    main()
